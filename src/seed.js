function seed() {
  for (const [k, v] of Object.entries(DEFAULT_SETTINGS)) {
    if (getSetting(k) === null) setSetting(k, v);
  }
  const t = now();
  const empty = (tbl) => db.prepare(`SELECT COUNT(*) c FROM ${tbl}`).get().c === 0;

  const tx = db.transaction(() => {
    if (empty('services')) {
      const st = db.prepare('INSERT INTO services (title, description, image, sort_order, published, created_at, updated_at) VALUES (?,?,?,?,1,?,?)');
      SERVICES.forEach(([a, b, img], i) => st.run(a, b, img, i + 1, t, t));
    }
    if (empty('project_categories') && empty('projects')) {
      const sc = db.prepare('INSERT INTO project_categories (name, sort_order, created_at, updated_at) VALUES (?,?,?,?)');
      const catIds = CATEGORIES.map((n, i) => sc.run(n, i + 1, t, t).lastInsertRowid);
      const sp = db.prepare(`INSERT INTO projects (title, category_id, location, area, summary, description, cover_image, before_image, after_image, is_demo, sort_order, published, created_at, updated_at)
        VALUES (?,?,?,?,?,?,?,?,?,1,?,1,?,?)`);
      const si = db.prepare('INSERT INTO project_images (project_id, image, alt, sort_order, created_at) VALUES (?,?,?,?,?)');
      PROJECTS.forEach(([title, c, img, desc], i) => {
        const id = sp.run(title, catIds[c], 'موقع تجريبي', '', desc, desc + ' (مشروع ورسوم توضيحية تجريبية — ليست أعمالًا فعلية للشركة).',
          `/img/demo/${img}`, '/img/demo/raw-shell-before', `/img/demo/${img}`, i + 1, t, t).lastInsertRowid;
        si.run(id, `/img/demo/${img}`, title, 1, t);
      });
    }
    if (empty('features')) {
      const st = db.prepare('INSERT INTO features (title, description, sort_order, published, created_at, updated_at) VALUES (?,?,?,1,?,?)');
      FEATURES.forEach(([a, b], i) => st.run(a, b, i + 1, t, t));
    }
    if (empty('steps')) {
      const st = db.prepare('INSERT INTO steps (title, description, sort_order, published, created_at, updated_at) VALUES (?,?,?,1,?,?)');
      STEPS.forEach(([a, b], i) => st.run(a, b, i + 1, t, t));
    }
    if (empty('faqs')) {
      const st = db.prepare('INSERT INTO faqs (question, answer, sort_order, published, created_at, updated_at) VALUES (?,?,?,1,?,?)');
      FAQS.forEach(([a, b], i) => st.run(a, b, i + 1, t, t));
    }
    // لا تُضاف آراء عملاء تجريبية عمدًا — الآراء تأتي من عملاء حقيقيين وبموافقتهم.
  });
  tx();
}

module.exports = { seed, DEFAULT_SETTINGS };
